-- 제품명 끝의 "⚠️규격" 꼬리표 제거.
--
-- 배경: 규격만 다른 형제 제품을 사람이 헷갈리지 않으려고 이름 뒤에 손으로 붙여둔 표시다.
--   예) "그린 케모포트니들 22G*19mm ⚠️1ea"(7,200) / "⚠️25ea"(195,000) — 27배 차이
-- 이제 자동배정이 규격을 직접 비교하고, 못 좁히면 사람에게 물어보므로(0017 이전 커밋)
-- 이 표시가 없어도 엉뚱한 형제가 선택되지 않는다.
--
-- 규격은 spec 칸에 이미 그대로 있어서 정보 손실이 없고,
-- 떼고 나면 원본 시트의 제품명과도 일치해 다음 단가 대조가 쉬워진다.
-- 이름이 같아지는 형제들은 spec 으로 구분된다(사전 확인: 이름+규격 충돌 0건).

update products
set name = trim(split_part(name, '⚠️', 1))
where name like '%⚠️%';
